// admin.proto — SecretAdminService: management plane for orange secret lifecycle.
//
// Operators and CI pipelines use this surface to create, rotate, retire,
// and audit secrets. The delivery path (SecretResolverService in
// orange.secret.v1) is handled separately.
//
// Every mutation emits a change event so connected SecretResolverService
// subscribers refresh without polling.
//
// # Encryption key hierarchy
//
//   MASTER_KEK  (external provider — never stored in the database)
//     ↓ wraps
//   SERVICE_KEK (stored in realm="system"; created via CreateServiceKEK)
//     ↓ wraps
//   DEK         (one per secret version)
//     ↓ encrypts
//   Secret material
//
// # KEK modes (configured server-side)
//
//   pooled (default)
//     A shared pool of SERVICE_KEKs is used for all boundaries. Pool members
//     are pre-allocated via CreateServiceKEK (empty workspace_id + realm).
//     Once the pool is warm, runtime DEK creation never requires MASTER_KEK
//     access. Set server-side PoolSize to auto-provision the pool on the
//     first CreateVersion call.
//
//   per-boundary
//     One dedicated SERVICE_KEK per (workspace_id, realm) pair. Stronger
//     isolation; requires MASTER_KEK access for every new boundary.
//
